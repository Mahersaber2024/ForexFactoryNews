import logging

logger = logging.getLogger(__name__)
NEW = ("hi", "ru", "id", "pt-BR", "vi")
_BY_EN = {en: sid for sid, en in SOURCE.items()}
_missing = set()


def t(language: str, en: str) -> str:
    """Translate an English UI string. fa/en and unknown languages get the text unchanged."""
    if language not in NEW or not isinstance(en, str) or not en:
        return en
    sid = _BY_EN.get(en)
    out = TRANSLATIONS.get(language, {}).get(sid) if sid else None
    if out:
        return out
    if (language, en) not in _missing:
        _missing.add((language, en))
        logger.debug(f"language: no {language} translation for {en[:60]!r}")
    return en


def pick(language: str, fa: str, en: str) -> str:
    """fa -> Persian text, any other language -> translated English text."""
    return fa if language == "fa" else t(language, en)


def table(language: str, en_table: dict, **overrides) -> dict:
    """Translate every string value of an English table (nested tuples/lists/dicts too).
    Keys given in `overrides` replace the automatic result (hand-made wording wins)."""
    def conv(v):
        if isinstance(v, str):
            return t(language, v)
        if isinstance(v, tuple):
            return tuple(conv(x) for x in v)
        if isinstance(v, list):
            return [conv(x) for x in v]
        if isinstance(v, dict):
            return {k: conv(x) for k, x in v.items()}
        return v
    out = {k: conv(v) for k, v in en_table.items()}
    out.update(overrides)
    return out


